"""Candidate wire contracts: immutable raw offsets, atomic facts, backend citations.

These are opt-in model contracts, not a migration of persisted Memory/Answer JSON.
Offset validity is provenance, never an entailment verdict.
"""
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, StrictInt, StrictStr, field_validator

from .query_schemas import (ANSWERABILITY_GUIDANCE, MULTI_ITEM_GUIDANCE, SHORT_ANSWER_GUIDANCE,
                            EVENT_IDENTITY_GUIDANCE)
from .temporal import QUERY_TIME_GUIDANCE

CONTRACT_VERSION = 'layered-evidence-v1'


class Contract(BaseModel):
    model_config = ConfigDict(extra='forbid')


class SourceSpan(Contract):
    source_id: StrictStr
    start: StrictInt = Field(ge=0)
    end: StrictInt = Field(gt=0)


class FactCandidate(Contract):
    content: StrictStr = Field(min_length=1)
    memory_type: Literal['event', 'state']
    statement_type: Literal['fact', 'plan', 'intention', 'uncertain']
    polarity: Literal['positive', 'negative']
    entity_id: StrictStr = Field(pattern=r'^[A-Za-z0-9][A-Za-z0-9_-]*$')
    state_dimension: StrictStr = Field(pattern=r'^[a-z][a-z0-9_]*$')
    state_value: StrictStr | None = None
    evidence: list[SourceSpan] = Field(min_length=1)
    # Separate spans permit discontinuous expressions without joining them into
    # a fabricated quote. All parts must belong to ONE fact-supporting source.
    time_spans: list[SourceSpan] = Field(default_factory=list)

    @field_validator('content')
    @classmethod
    def nonblank(cls, value):
        if not value.strip():
            raise ValueError('Blank fact')
        return value


class CandidateBatch(Contract):
    # Deliberately validate records separately: one malformed record must not
    # cause valid siblings to be regenerated. Invalid top-level JSON stops.
    records: list[dict] = Field(max_length=128)
    no_facts_reason: StrictStr | None = None


class AnswerSupport(Contract):
    memory_id: StrictStr | None = None
    # Position in the supplied memory's source_ids, or in raw_sources for raw
    # answers. The model never emits a SourceTurn ID at this boundary.
    source_index: StrictInt = Field(ge=0)
    start: StrictInt = Field(ge=0)
    end: StrictInt = Field(gt=0)


class AnswerClaim(Contract):
    text: StrictStr = Field(min_length=1)
    supports: list[AnswerSupport] = Field(min_length=1)

    @field_validator('text')
    @classmethod
    def nonblank(cls, value):
        if not value.strip():
            raise ValueError('Blank answer claim')
        return value


class AnswerCandidate(Contract):
    status: Literal['sufficient', 'conflict', 'insufficient']
    claims: list[AnswerClaim]
    explanation: StrictStr | None = None


class SupportVerdict(Contract):
    verdict: Literal['entailed', 'unsupported', 'unknown']
    # Static codes, not hidden reasoning or copied provider prose.
    issue: Literal['none', 'entity', 'polarity', 'modality', 'event_link',
                   'time', 'citation', 'coverage', 'other']


